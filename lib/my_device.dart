class MotoDeviceState {
  final bool loading;
  final String? error;
  final MotoDevice? device;

  const MotoDeviceState({
    this.loading = true,
    this.error,
    this.device,
  });
}

// ======================================================================
// ESP STATUS
// ======================================================================

enum EspLink {
  idle,
  connecting,
  connected,
  reconnecting,
  disconnected,
}

class EspStatus {
  final EspLink link;

  /// Firebase server timestamp.
  final int? lastUpdateMs;

  /// Timestamp generated by the ESP32/device.
  final int? deviceTimestamp;

  final int? satellites;

  final double? speedKmh;

  final double? latitude;
  final double? longitude;

  final double? altitude;
  final double? accuracy;
  final double? hdop;

  final String? status;

  final bool gpsFix;

  const EspStatus({
    this.link = EspLink.idle,
    this.lastUpdateMs,
    this.deviceTimestamp,
    this.satellites,
    this.speedKmh,
    this.latitude,
    this.longitude,
    this.altitude,
    this.accuracy,
    this.hdop,
    this.status,
    this.gpsFix = false,
  });
}

// ======================================================================
// SHARED DEVICE REGISTRY
// ======================================================================

class MotoDeviceRegistry {
  MotoDeviceRegistry._();

  static final MotoDeviceRegistry instance = MotoDeviceRegistry._();

  final ValueNotifier<MotoDeviceState> state = ValueNotifier<MotoDeviceState>(
    const MotoDeviceState(),
  );

  final ValueNotifier<EspStatus> esp = ValueNotifier<EspStatus>(
    const EspStatus(),
  );

  int _users = 0;

  StreamSubscription<User?>? _authSub;

  StreamSubscription<QuerySnapshot<Map<String, dynamic>>>? _deviceSub;

  // ====================================================================
  // RTDB
  // ====================================================================

  FirebaseDatabase? _rtdb;

  FirebaseDatabase get _db {
    return _rtdb ??= FirebaseDatabase.instanceFor(
      app: Firebase.app(),
      databaseURL: kMotoRtdbUrl,
    );
  }

  StreamSubscription<DatabaseEvent>? _hbSub;

  StreamSubscription<DatabaseEvent>? _offsetSub;

  Timer? _hbTimer;

  String? _hbDeviceId;

  bool _everSeen = false;

  int _offsetMs = 0;

  final Stopwatch _clock = Stopwatch()..start();

  int _startedMs = 0;

  int _lastChangeMs = 0;

  int _lastReattachMs = 0;

  int? _lastSeq;

  int? _lastUpdatedAt;

  int? _satellites;

  double? _speed;

  bool _gpsFix = false;

  // ====================================================================
  // RETAIN
  // ====================================================================

  void retain() {
    _users++;

    if (_users != 1) {
      return;
    }

    _offsetSub = _db.ref('.info/serverTimeOffset').onValue.listen(
      (event) {
        final value = event.snapshot.value;

        if (value is num) {
          _offsetMs = value.toInt();
        }
      },
      onError: (_) {},
    );

    _authSub = FirebaseAuth.instance.authStateChanges().listen(
          _bind,
        );
  }

  // ====================================================================
  // RELEASE
  // ====================================================================

  void release() {
    if (_users > 0) {
      _users--;
    }

    if (_users != 0) {
      return;
    }

    _authSub?.cancel();
    _authSub = null;

    _deviceSub?.cancel();
    _deviceSub = null;

    _offsetSub?.cancel();
    _offsetSub = null;

    _stopHeartbeat();

    state.value = const MotoDeviceState(
      loading: false,
    );
  }

  // ====================================================================
  // BIND CURRENT USER
  // ====================================================================

  void _bind(User? user) {
    _deviceSub?.cancel();
    _deviceSub = null;

    _stopHeartbeat();

    if (user == null) {
      state.value = const MotoDeviceState(
        loading: false,
      );

      return;
    }

    state.value = const MotoDeviceState();

    // ================================================================
    // Only listen to devices belonging to the current user.
    // ================================================================

    _deviceSub = FirebaseFirestore.instance
        .collection(kMotorDevicesCollection)
        .where(
          'connectedUserId',
          isEqualTo: user.uid,
        )
        .limit(1)
        .snapshots()
        .listen(
      (snapshot) {
        final device = snapshot.docs.isEmpty
            ? null
            : MotoDevice.fromDoc(
                snapshot.docs.first,
              );

        state.value = MotoDeviceState(
          loading: false,
          device: device,
        );

        if (device == null) {
          _stopHeartbeat();
        } else {
          _startHeartbeat(device.id);
        }
      },
      onError: (_) {
        state.value = MotoDeviceState(
          loading: false,
          error: 'Unable to load your device.',
          device: state.value.device,
        );
      },
    );
  }

  // ====================================================================
  // LIVE ESP32 HEARTBEAT
  // ====================================================================

  void _startHeartbeat(
    String deviceId,
  ) {
    if (_hbDeviceId == deviceId && _hbSub != null) {
      return;
    }

    _stopHeartbeat();

    _hbDeviceId = deviceId;

    _everSeen = false;

    _startedMs = _clock.elapsedMilliseconds;

    _lastChangeMs = _startedMs;

    _lastReattachMs = _startedMs;

    esp.value = const EspStatus(
      link: EspLink.connecting,
    );

    _attachHeartbeat();

    _hbTimer = Timer.periodic(
      const Duration(seconds: 1),
      (_) => _evaluateHeartbeat(),
    );
  }

  // ====================================================================
  // ATTACH RTDB LISTENER
  // ====================================================================

  void _attachHeartbeat() {
    final id = _hbDeviceId;

    if (id == null) {
      return;
    }

    _hbSub?.cancel();

    _hbSub = _db.ref('gps/$id').onValue.listen(
          _onHeartbeat,
          onError: (_) {},
        );
  }

  // ====================================================================
  // RECEIVE RTDB DATA
  // ====================================================================

  void _onHeartbeat(
    DatabaseEvent event,
  ) {
    final value = event.snapshot.value;

    if (value is! Map) {
      return;
    }

    // ---------------------------------------------------------------
    // Heartbeat fields
    // ---------------------------------------------------------------

    final updatedAt = _toInt(
      value['updatedAt'],
    );

    final seq = _toInt(
      value['seq'],
    );

    if (updatedAt != _lastUpdatedAt || seq != _lastSeq) {
      _lastUpdatedAt = updatedAt;
      _lastSeq = seq;

      _lastChangeMs = _clock.elapsedMilliseconds;
    }

    // ---------------------------------------------------------------
    // GPS fields
    // ---------------------------------------------------------------

    final satellites = _toInt(
      value['satellites'],
    );

    final speed = _toDouble(
      value['speed'],
    );

    final latitude = _toDouble(
      value['latitude'],
    );

    final longitude = _toDouble(
      value['longitude'],
    );

    final altitude = _toDouble(
      value['altitude'],
    );

    final accuracy = _toDouble(
      value['accuracy'],
    );

    final hdop = _toDouble(
      value['hdop'],
    );

    final deviceTimestamp = _toInt(
      value['deviceTimestamp'],
    );

    final gpsFix = _toBool(
      value['gpsFix'],
    );

    final gpsStatus = value['status']?.toString();

    // ---------------------------------------------------------------
    // Cache basic heartbeat values
    // ---------------------------------------------------------------

    _satellites = satellites;

    _speed = speed;

    _gpsFix = gpsFix;

    // ---------------------------------------------------------------
    // Evaluate connection state.
    //
    // This updates the EspStatus and preserves the GPS fields.
    // ---------------------------------------------------------------

    _evaluateHeartbeat(
      latitude: latitude,
      longitude: longitude,
      altitude: altitude,
      accuracy: accuracy,
      hdop: hdop,
      deviceTimestamp: deviceTimestamp,
      gpsStatus: gpsStatus,
    );
  }

  // ====================================================================
  // HEARTBEAT EVALUATION
  // ====================================================================

  void _evaluateHeartbeat({
    double? latitude,
    double? longitude,
    double? altitude,
    double? accuracy,
    double? hdop,
    int? deviceTimestamp,
    String? gpsStatus,
  }) {
    if (_hbDeviceId == null) {
      return;
    }

    final now = _clock.elapsedMilliseconds;

    final silence = now - _lastChangeMs;

    final updatedAt = _lastUpdatedAt;

    final serverNow = DateTime.now().millisecondsSinceEpoch + _offsetMs;

    final age = updatedAt == null ? null : serverNow - updatedAt;

    final alive = age != null &&
        age <= kHeartbeatTimeoutMs &&
        age >= -kClockToleranceMs &&
        silence <= kHeartbeatTimeoutMs;

    EspLink link;

    if (alive) {
      _everSeen = true;

      link = EspLink.connected;
    } else if (_everSeen) {
      link = EspLink.reconnecting;
    } else if (updatedAt == null && now - _startedMs < 6000) {
      link = EspLink.connecting;
    } else {
      link = EspLink.disconnected;
    }

    // ================================================================
    // AUTO RECONNECT
    // ================================================================

    if (!alive && now - _lastReattachMs >= kReattachEveryMs) {
      _lastReattachMs = now;

      _db.goOnline();

      _attachHeartbeat();
    }

    // ================================================================
    // Preserve existing GPS data if this call is only a heartbeat
    // evaluation.
    // ================================================================

    final current = esp.value;

    esp.value = EspStatus(
      link: link,
      lastUpdateMs: updatedAt,
      deviceTimestamp: deviceTimestamp ?? current.deviceTimestamp,
      satellites: _satellites,
      speedKmh: _speed,
      latitude: latitude ?? current.latitude,
      longitude: longitude ?? current.longitude,
      altitude: altitude ?? current.altitude,
      accuracy: accuracy ?? current.accuracy,
      hdop: hdop ?? current.hdop,
      status: gpsStatus ?? current.status,
      gpsFix: _gpsFix,
    );
  }

  // ====================================================================
  // STOP HEARTBEAT
  // ====================================================================

  void _stopHeartbeat() {
    _hbTimer?.cancel();

    _hbTimer = null;

    _hbSub?.cancel();

    _hbSub = null;

    _hbDeviceId = null;

    _everSeen = false;

    _lastSeq = null;

    _lastUpdatedAt = null;

    _satellites = null;

    _speed = null;

    _gpsFix = false;

    if (esp.value.link != EspLink.idle) {
      esp.value = const EspStatus();
    }
  }

  // ====================================================================
  // REMOVE DEVICE
  //
  // NO CLOUD FUNCTIONS.
  //
  // Firestore Rules verify that the current user owns the device.
  // ====================================================================

  Future<void> removeDevice(
    String deviceId,
  ) async {
    final user = FirebaseAuth.instance.currentUser;

    if (user == null) {
      throw FirebaseException(
        plugin: 'firebase_auth',
        code: 'unauthenticated',
        message: 'Please login first.',
      );
    }

    final ref = FirebaseFirestore.instance
        .collection(kMotorDevicesCollection)
        .doc(deviceId);

    await ref.update({
      'status': 'available',
      'connectedUserId': '',
      'connectedAt': FieldValue.delete(),
    });
  }
}

