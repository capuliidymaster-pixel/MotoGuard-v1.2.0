    final connected = esp.link == EspLink.connected;

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        // ============================================================
        // CONNECTION STATUS
        // ============================================================

        Row(
          children: [
            Icon(
              Icons.circle,
              color: color,
              size: 10,
