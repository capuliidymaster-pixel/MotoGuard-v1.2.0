class MotoDevice {
  final String id;
  final String name;
  final Map<String, dynamic> data;

  const MotoDevice({
    required this.id,
    required this.name,
    required this.data,
  });

  factory MotoDevice.fromDoc(
    QueryDocumentSnapshot<Map<String, dynamic>> doc,
  ) {
    final data = doc.data();

    final rawName = data['name']?.toString().trim();
    final rawDeviceId = data['deviceId']?.toString().trim();

    final deviceId =
        rawDeviceId != null && rawDeviceId.isNotEmpty ? rawDeviceId : doc.id;

    return MotoDevice(
      id: deviceId,
      name:
          rawName != null && rawName.isNotEmpty ? rawName : kDefaultDeviceName,
      data: data,
    );
  }
}

