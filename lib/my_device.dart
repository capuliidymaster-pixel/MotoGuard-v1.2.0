    EspStatus esp,
  ) {
    Color color;

    String label;

    switch (esp.link) {
      case EspLink.connected:
        color = cyberGreen;
        label = 'ESP32 CONNECTED';
        break;

      case EspLink.reconnecting:
        color = Colors.orangeAccent;
        label = 'ESP32 DISCONNECTED - RECONNECTING...';
        break;

      case EspLink.disconnected:
        color = Colors.redAccent;
        label = 'ESP32 OFFLINE - RETRYING...';
        break;

      case EspLink.connecting:
      case EspLink.idle:
        color = Colors.grey;
        label = 'CONNECTING TO ESP32...';
        break;
