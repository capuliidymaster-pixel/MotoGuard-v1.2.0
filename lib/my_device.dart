  // REMOVE DEVICE
  // ====================================================================

  Future<void> removeDevice(
    MotoDevice device,
  ) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (dialogContext) {
        return AlertDialog(
          backgroundColor: const Color(0xFF0A1711),
          title: const Text(
            'Remove Device?',
            style: TextStyle(
              color: Colors.white,
            ),
          ),
          content: const Text(
            'This will remove the motorcycle '
            'from your account. The device can '
            'then be registered by another account.',
            style: TextStyle(
              color: Colors.white70,
            ),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(
                dialogContext,
                false,
              ),
              child: const Text(
                'CANCEL',
                style: TextStyle(
                  color: Colors.white54,
                ),
              ),
            ),
            TextButton(
              onPressed: () => Navigator.pop(
                dialogContext,
                true,
              ),
              child: const Text(
                'REMOVE',
                style: TextStyle(
                  color: Colors.redAccent,
                ),
              ),
            ),
          ],
        );
      },
    );

    if (confirmed != true || !mounted) {
      return;
    }

    setState(() {
      _busy = true;
    });

    try {
      await _registry.removeDevice(
        device.id,
      );

      if (!mounted) {
        return;
      }

      setState(() {
        _busy = false;
      });

      showMessage(
        'Device removed successfully.',
      );
    } on FirebaseException catch (e) {
      if (!mounted) {
        return;
      }

      setState(() {
        _busy = false;
      });

      if (e.code == 'permission-denied') {
        showMessage(
          'You are not allowed to remove this device.',
        );
      } else if (e.code == 'not-found') {
        showMessage(
          'Device was not found.',
        );
      } else {
        showMessage(
          e.message ?? 'Unable to remove device.',
        );
      }
    } catch (_) {
      if (!mounted) {
        return;
      }

      setState(() {
        _busy = false;
      });

      showMessage(
        'Unable to remove device.',
      );
    }
  }

