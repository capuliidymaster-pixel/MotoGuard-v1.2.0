              ? esp.gpsFix
                  ? 'Yes'
                  : 'Searching...'
              : '--',
        ),

        _infoRow(
          'Satellites',
          connected ? esp.satellites?.toString() ?? '--' : '--',
        ),

        _infoRow(
          'Speed',
          connected && esp.speedKmh != null
              ? '${esp.speedKmh!.toStringAsFixed(1)} km/h'
              : '--',
        ),

        _infoRow(
          'Latitude',
          connected && esp.latitude != null
              ? esp.latitude!.toStringAsFixed(6)
              : '--',
        ),

        _infoRow(
          'Longitude',
          connected && esp.longitude != null
              ? esp.longitude!.toStringAsFixed(6)
              : '--',
        ),

        _infoRow(
          'Altitude',
          connected && esp.altitude != null
              ? '${esp.altitude!.toStringAsFixed(1)} m'
              : '--',
        ),

        _infoRow(
          'Accuracy',
          connected && esp.accuracy != null
              ? '${esp.accuracy!.toStringAsFixed(1)} m'
              : '--',
        ),

        _infoRow(
          'HDOP',
          connected && esp.hdop != null ? esp.hdop!.toStringAsFixed(1) : '--',
        ),

        _infoRow(
          'Status',
          connected && esp.status != null ? esp.status! : '--',
        ),

        _infoRow(
          'Device time',
          _fmtClock(
            esp.deviceTimestamp,
          ),
        ),
      ],
    );
  }

