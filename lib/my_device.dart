  // ====================================================================
  // CLOCK
  // ====================================================================

  String _fmtClock(
    int? ms,
  ) {
    if (ms == null) {
      return '--:--:--';
    }

    final d = DateTime.fromMillisecondsSinceEpoch(
      ms,
    ).toLocal();

    String two(int n) => n.toString().padLeft(2, '0');

    return '${two(d.hour)}:'
        '${two(d.minute)}:'
        '${two(d.second)}';
  }

