const int kClockToleranceMs = 10000;
const int kReattachEveryMs = 10000;

// ======================================================================
// HELPERS
// ======================================================================

int? _toInt(Object? value) {
  if (value is int) {
    return value;
  }

  if (value is num) {
    return value.toInt();
  }

  if (value is String) {
    return int.tryParse(value.trim());
  }

  return null;
}

double? _toDouble(Object? value) {
  if (value is num) {
    final d = value.toDouble();

    return d.isFinite ? d : null;
  }

  if (value is String) {
    final d = double.tryParse(value.trim());

    if (d != null && d.isFinite) {
      return d;
    }
  }

  return null;
}

bool _toBool(Object? value) {
  if (value is bool) {
    return value;
  }

  if (value is String) {
    return value.trim().toLowerCase() == 'true';
  }

  if (value is num) {
    return value != 0;
  }

  return false;
}

